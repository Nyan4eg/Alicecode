const { contextBridge, ipcRenderer, webUtils } = require('electron');

const invoke = (name) => (...args) => ipcRenderer.invoke(name, ...args);
const subscribe = (name) => (fn) => ipcRenderer.on(name, (_event, data) => fn(data));

contextBridge.exposeInMainWorld('alicecode', {
  state: invoke('app:state'),
  taskOptions: invoke('task:options'),
  instructions: invoke('project:instructions'),
  saveInstructions: invoke('project:save-instructions'),
  planTask: invoke('task:plan'),
  taskWorkspace: invoke('task:workspace'),
  transferPreview: invoke('task:transfer-preview'),
  transferTask: invoke('task:transfer'),
  resumeTask: invoke('task:resume'),
  saveWorkspace: invoke('workspace:save'),
  flushWorkspace: values => ipcRenderer.sendSync('workspace:flush', values),
  selectMode: invoke('chat:mode'),
  copyText: invoke('app:copy'),
  openExternal: invoke('app:open-external'),
  createProject: invoke('project:create'),
  chooseFolder: invoke('project:choose'),
  openProject: invoke('project:open'),
  revealProject: invoke('project:reveal'),
  inspectProject: invoke('project:inspect'),
  listDirectory: invoke('project:directory'),
  searchFiles: invoke('project:search-files'),
  searchContent: invoke('project:search-content'),
  readFile: invoke('project:read'),
  readEditor: invoke('project:editor'),
  saveFile: invoke('project:save-file'),
  readDiff: invoke('project:diff'),
  previewContext: invoke('project:context'),
  chooseAttachments: invoke('attachment:choose'),
  dropAttachments(chatId, files) {
    const paths = files.map(file => webUtils.getPathForFile(file)).filter(Boolean);
    return ipcRenderer.invoke('attachment:drop', chatId, paths);
  },
  previewAttachment: invoke('attachment:preview'),
  attachFiles: invoke('attachment:attach'),
  removeAttachment: invoke('attachment:remove'),
  readAttachment: invoke('attachment:read'),
  readReviewFile: invoke('chat:review-file'),
  rollbackPreview: invoke('chat:rollback-preview'),
  rollback: invoke('chat:rollback'),
  stageFile: invoke('git:stage'),
  gitHunks: invoke('git:hunks'),
  stageHunks: invoke('git:stage-hunks'),
  commitPreview: invoke('git:commit-preview'),
  commit: invoke('git:commit'),
  selectProject: invoke('project:select'),
  renameProject: invoke('project:rename'),
  newChat: invoke('chat:new'),
  selectChat: invoke('chat:select'),
  renameChat: invoke('chat:rename'),
  archiveChat: invoke('chat:archive'),
  deleteChat: invoke('chat:delete'),
  selectModel: invoke('chat:model'),
  search: invoke('history:search'),
  send: invoke('chat:send'),
  stop: invoke('chat:stop'),
  permission: invoke('chat:permission'),
  replayDetails: invoke('chat:replay-details'),
  replayTest: invoke('chat:replay-test'),
  saveKey: invoke('settings:save'),
  checkProvider: invoke('settings:check-provider'),
  saveLayout: invoke('settings:layout'),
  refreshModels: invoke('settings:models'),
  checkUpdates: invoke('updates:check'),
  installUpdate: invoke('updates:install'),
  onState: subscribe('app:state'),
  onMessage: subscribe('chat:message'),
  onUpdate: subscribe('app:update'),
  onCatalog: subscribe('app:catalog'),
});
