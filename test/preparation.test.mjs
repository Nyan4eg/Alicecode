import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm, appendFile, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { Store } from '../app/store.mjs';
import { CommandRuns, commandProfile } from '../app/project-commands.mjs';
import { AffectedChecks } from '../app/affected-checks.mjs';

test('environment preparation persists per root, skips checks on failure and invalidates by environment inputs', async t => {
  const home = await realpath(await mkdtemp(join(tmpdir(),'alice-prep-')));
  const root = join(home,'src'), database = join(home,'app.sqlite');
  await mkdir(root); execFileSync('git',['init','-q'],{cwd:root});
  let store = new Store(database);
  let commands = new CommandRuns(store,()=>{}), checks = new AffectedChecks(store,commands);
  t.after(async()=>{await commands.close();store.db.close();await rm(home,{recursive:true,force:true});});
  const chat = store.addProject('A',root);
  const script = 'node prepare.cjs', ids = ['api','web'];
  store.saveProfile(chat.projectId,commandProfile({commands:{prepare:script}}));
  for (const id of ids) {
    await mkdir(join(root,id));
    store.putProfile(chat,commandProfile({id,name:id,directory:id,scope:[id,'shared'],commands:{test:'node --version'}}));
  }
  await writeFile(join(root,'package.json'),'{"private":true}');
  await writeFile(join(root,'package-lock.json'),'{}');
  await writeFile(join(root,'.gitignore'),'node_modules/\n');
  await writeFile(join(root,'prepare.cjs'),"const fs=require('fs');if(!fs.existsSync('allow'))process.exit(2);fs.mkdirSync('node_modules',{recursive:true})");
  const current = store.chat(chat.id);
  const inspect = () => checks.preparation.inspect(current);
  const runs = () => store.commands().filter(run=>run.preparation);
  assert.equal((await inspect()).inputs.command,script);
  await checks.run(current,ids); assert.equal(runs().length,1); assert.equal(runs()[0].exitCode,2);
  assert.deepEqual((await checks.summary(current)).rows.map(p=>p.status),['skipped','skipped']);
  assert.equal(store.commands().filter(run=>run.steps).length,0);
  await writeFile(join(root,'allow'),'');
  await checks.run(current,ids);assert.equal((await inspect()).status,'ready');
  assert.equal(runs().length,2);
  const web = store.latestSequence(chat.id,root,'web').id;
  await writeFile(join(root,'api','change.ts'),'');
  await checks.run(current,ids);assert.equal(store.latestSequence(chat.id,root,'web').id,web);
  await commands.close();store.db.close();store = new Store(database);commands=new CommandRuns(store,()=>{});checks=new AffectedChecks(store,commands);
  assert.equal((await inspect()).status,'ready');await checks.run(current,ids);assert.equal(runs().length,2);
  const last = runs()[0];
  store.saveCommand({...last,preparation:{...last.preparation,inputs:{...last.preparation.inputs,node:'v0.0.1'}}});
  assert.match((await inspect()).reason,/Node.js/);store.saveCommand(last);
  const other = join(home,'other');await mkdir(other);
  assert.equal((await checks.preparation.inspect(current,other)).status,'needed');
  await appendFile(join(root,'package-lock.json'),'\n');assert.match((await inspect()).reason,/package-lock/);
  await writeFile(join(root,'package-lock.json'),'{}');
  await rm(join(root,'node_modules'),{recursive:true});assert.match((await inspect()).reason,/node_modules/);
  await mkdir(join(root,'node_modules'));
  store.saveProfile(chat.projectId,commandProfile({commands:{prepare:'node prepare.cjs --setup'}}));
  assert.match((await inspect()).reason,/команда/);
  await writeFile(join(root,'package.json'),'{"workspaces":["web","api"]}');
  await writeFile(join(root,'web','package.json'),'{"name":"web"}');
  store.putProfile(chat,commandProfile({id:'web',name:'Web',directory:'web',commands:{prepare:'npm ci'}}));
  const nested = await inspect();
  assert.equal(nested.cwd,join(root,'web')); assert.equal(nested.modulesDirectory,'node_modules');
  assert.equal(nested.lock,'package-lock.json'); assert.ok(nested.inputs.files['web/package.json']);
});
